function postShareText(post) {
  const title = post.demo ? text(post.titleKey) : post.title;
  const body = post.demo ? text(post.bodyKey) : post.body;
  const area = post.demo ? text(post.areaKey) : (post.area || "Malvan");
  const contact = post.contact ? `\n${language === "mr" ? "संपर्क" : "Contact"}: ${post.contact}` : "";
  return `${categoryName(post.category)} · ${title}\n${body}\n${area}${contact}\n\nMalvan Connect`;
}

async function sharePost(post) {
  const shareData = { title: "Malvan Connect", text: postShareText(post) };
  try {
    const files = [];
    for (const attachment of post.media || []) {
      const blob = await loadMediaFile(attachment.id);
      if (blob) files.push(new File([blob], attachment.name, { type: attachment.type || blob.type }));
    }
    if (navigator.share && files.length && navigator.canShare?.({ files })) await navigator.share({ ...shareData, files });
    else if (navigator.share) {
      await navigator.share(shareData);
      if (files.length) showToast(text("mediaShareFallback"));
    }
    else {
      await navigator.clipboard.writeText(shareData.text);
      showToast(files.length ? text("mediaShareFallback") : text("copied"));
    }
  } catch (error) {
    if (error.name !== "AbortError") showToast(text("shareError"));
  }
}

