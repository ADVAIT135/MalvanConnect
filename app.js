function renderMoon() {
  const synodicMonth = 29.530588853;
  const reference = Date.UTC(2000, 0, 6, 18, 14);
  const phase = (((Date.now() - reference) / 86400000) % synodicMonth + synodicMonth) % synodicMonth / synodicMonth;
  const illumination = Math.round((1 - Math.cos(phase * Math.PI * 2)) * 50);
  const names = featureText[language].moonNames;
  const phaseIndex = Math.round(phase * 8) % 8;
  document.querySelector("#moon-name").textContent = names[phaseIndex];
  document.querySelector("#moon-illumination").textContent = `${illumination}% illuminated`;
  document.querySelector("#moon-visual").className = `moon-visual moon-${phaseIndex}`;
}

function renderTides(data) {
  const times = data.hourly.time;
  const levels = data.hourly.sea_level_height_msl;
  const waves = data.hourly.wave_height;
  const currents = data.hourly.ocean_current_velocity;
  const today = dateInMalvan();
  const todayReadings = times.map((time, index) => ({ time, level: levels[index], wave: waves[index], current: currents[index] }))
    .filter(item => item.time.startsWith(today) && Number.isFinite(item.level));
  const turns = [];
  for (let index = 1; index < todayReadings.length - 1; index += 1) {
    const previous = todayReadings[index - 1].level;
    const current = todayReadings[index].level;
    const next = todayReadings[index + 1].level;
    if (current > previous && current >= next) turns.push({ ...todayReadings[index], kind: "high" });
    if (current < previous && current <= next) turns.push({ ...todayReadings[index], kind: "low" });
  }

  const turnsTarget = document.querySelector("#tide-turns");
  if (!turns.length) setMessage(turnsTarget, text("noTurns"));
  else {
    turnsTarget.replaceChildren(...turns.slice(0, 4).map(turn => {
      const row = document.createElement("div");
      row.className = `turn-row ${turn.kind}`;
      const label = document.createElement("span");
      label.textContent = text(turn.kind);
      const time = document.createElement("strong");
      time.textContent = displayHour(turn.time.slice(11, 16));
      const height = document.createElement("span");
      height.textContent = `${turn.level.toFixed(2)} m`;
      row.append(label, time, height);
      return row;
    }));
  }

  const currentHour = currentHourInMalvan();
  const available = times.map((time, index) => ({ time, wave: waves[index], current: currents[index] }))
    .filter(item => item.time.startsWith(today) && Number.isFinite(item.wave) && Number.isFinite(item.current) && Number(item.time.slice(11, 13)) >= currentHour);
  available.sort((left, right) => left.wave + left.current / 5 - (right.wave + right.current / 5));
  const best = available[0];
  document.querySelector("#fishing-window").textContent = best
    ? `${text("calmest")}: ${displayHour(best.time.slice(11, 16))} · ${best.wave.toFixed(1)} m waves`
    : text("noWindow");

  const nextReadings = times.map((time, index) => ({ time, level: levels[index], wave: waves[index], current: currents[index] }))
    .filter(item => item.time >= `${today}T${String(currentHour).padStart(2, "0")}:00` && Number.isFinite(item.wave));
  const selected = nextReadings.filter((_, index) => index % 3 === 0).slice(0, 5);
  const forecastTarget = document.querySelector("#sea-forecast");
  forecastTarget.replaceChildren(...selected.map(item => {
    const row = document.createElement("div");
    row.className = "sea-hour";
    const time = document.createElement("strong");
    time.textContent = displayHour(item.time.slice(11, 16));
    const wave = document.createElement("span");
    wave.innerHTML = `<small>${text("waves")}</small>${Number.isFinite(item.wave) ? `${item.wave.toFixed(1)} m` : "—"}`;
    const current = document.createElement("span");
    current.innerHTML = `<small>${text("current")}</small>${Number.isFinite(item.current) ? `${item.current.toFixed(1)} km/h` : "—"}`;
    const level = document.createElement("span");
    level.innerHTML = `<small>${text("tideHeight")}</small>${Number.isFinite(item.level) ? `${item.level.toFixed(2)} m` : "—"}`;
    row.append(time, wave, current, level);
    return row;
  }));
}

